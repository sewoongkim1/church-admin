// 그 날짜의 공휴일 이름("" = 공휴일이 아니다 · 표 밖의 날짜 · 날짜가 아닌 값)
export function holidayName(date) {
  const s = String(date ?? "").slice(0, 10);
  return Object.prototype.hasOwnProperty.call(HOLIDAYS, s) ? HOLIDAYS[s] : "";
}
// 그 달(ym = "YYYY-MM")이 표가 덮는 기간 밖인가 → "before"(표가 시작하기 전) · "after"(표 끝 뒤) · ""(안 — 또는 달이 아닌 값)
export function holOutside(ym) {
  const s = String(ym ?? "");
  if (!/^\d{4}-\d{2}$/.test(s)) return "";
  return s < HOL_FROM.slice(0, 7) ? "before" : s > HOL_UNTIL.slice(0, 7) ? "after" : "";
}
// 표 밖의 달에 달력 풀이가 하는 말(성경암송 앱 달력과 같은 글 — js/duty.js dutyHolOutsideText)
const ymWord = (ds) => `${Number(ds.slice(0, 4))}년 ${Number(ds.slice(5, 7))}월`;
export const holOutsideText = (side) => (side === "after" ? `이 달의 공휴일은 아직 표시되지 않아요(${ymWord(HOL_UNTIL)}까지만 빨갛게 보여요).`
  : side === "before" ? `이 달의 공휴일은 표시되지 않아요(${ymWord(HOL_FROM)}부터 빨갛게 보여요).` : "");
// 한 달의 칸들(duty-logic.js calMonth — [{ date, n }])에서 공휴일을 풀이의 조각으로 — ["3일 개천절", "5일 대체공휴일", "9일 한글날"] · 이어진 같은 이름은 「14~16일 추석」
export function holItems(cells) {
  const out = [];
  let cur = null;
  for (const c of cells || []) {
    const name = c && c.date ? holidayName(c.date) : "";
    if (name && cur && cur.name === name && cur.to === c.n - 1) { cur.to = c.n; continue; }
    cur = name ? { name, from: c.n, to: c.n } : null;
    if (cur) out.push(cur);
  }
  return out.map((x) => `${x.from === x.to ? `${x.from}일` : `${x.from}~${x.to}일`} ${x.name}`);
}
